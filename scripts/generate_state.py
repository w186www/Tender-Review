"""Generate LangGraph types from the sole State JSON Schema source."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def python_type(schema: dict[str, object], classes: list[str], name: str) -> str:
    if "const" in schema:
        return f"Literal[{json.dumps(schema['const'])}]"
    if "enum" in schema:
        values = ", ".join(json.dumps(item) for item in schema["enum"])
        inline = f"Literal[{values}]"
        if len(inline) > 88:
            return f"Literal[\n        {values}\n    ]"
        return inline
    if "$ref" in schema:
        # Domain findings are validated with their own JSON Schema at boundaries.
        return "dict[str, object]"
    value = schema.get("type")
    if isinstance(value, list):
        return " | ".join(python_type({"type": item}, classes, name) for item in value)
    if value == "array":
        return f"list[{python_type(schema['items'], classes, name + 'Item')}]"
    if value == "object" and "properties" in schema:
        emit_class(schema, classes, name)
        return name
    types = {
        "string": "str",
        "integer": "int",
        "number": "float",
        "boolean": "bool",
        "null": "None",
        "object": "dict[str, object]",
    }
    if value not in types:
        raise ValueError(f"unsupported schema type: {value!r}")
    return types[value]


def emit_class(schema: dict[str, object], classes: list[str], name: str) -> None:
    required = set(schema.get("required", []))
    fields = []
    for key, spec in schema["properties"].items():
        field_type = python_type(spec, classes, name + key.title().replace("_", ""))
        reducer = spec.get("x-reducer")
        if reducer is not None:
            if reducer != "merge_sorted_unique" or not field_type.startswith("list["):
                raise ValueError(f"unsupported reducer: {reducer!r}")
            field_type = f"Annotated[{field_type}, merge_sorted_unique]"
        if key not in required:
            field_type = f"NotRequired[{field_type}]"
        declaration = f"    {key}: {field_type}"
        if len(declaration) > 100:
            declaration += "  # noqa: E501"
        fields.append(declaration)
    classes.append(f"class {name}(TypedDict):\n" + "\n".join(fields))


def render_state(root: Path = ROOT) -> str:
    schema = json.loads(
        (root / "contracts/schemas/compliance-state.schema.json").read_text(encoding="utf-8")
    )
    classes: list[str] = []
    emit_class(schema, classes, "ComplianceReviewState")
    return (
        '"""Generated by scripts/generate_state.py; edit the JSON Schema, not this file."""\n\n'
        "from typing import Annotated, Literal, NotRequired, TypedDict\n\n"
        "from bidding_compliance.graph.reducers import merge_sorted_unique\n\n\n"
        + "\n\n\n".join(classes)
        + "\n"
    )


def check_state(root: Path = ROOT) -> bool:
    target = root / "src/bidding_compliance/graph/state.py"
    return target.exists() and target.read_text(encoding="utf-8") == render_state(root)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        if not check_state():
            print("ERROR: generated State is stale; run scripts/generate_state.py")
            return 1
        return 0
    (ROOT / "src/bidding_compliance/graph/state.py").write_text(
        render_state(), encoding="utf-8", newline="\n"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
